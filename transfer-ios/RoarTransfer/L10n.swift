import SwiftUI

// EN / GR, as the website's switch: English is the key, Greek from the website's own words where it has them.
// Greek on a phone set to Greek, until the person picks.
@MainActor
final class Lang: ObservableObject {
    static let shared = Lang()
    @Published var code: String {
        didSet { UserDefaults.standard.set(code, forKey: "lang") }
    }
    init() {
        code = UserDefaults.standard.string(forKey: "lang") ?? (Locale.preferredLanguages.contains { $0.hasPrefix("el") } || TimeZone.current.identifier == "Europe/Athens" || TimeZone.current.identifier == "Asia/Nicosia" ? "el" : "en")
    }
    var el: Bool { code == "el" }
}

@MainActor
func t(_ en: String) -> String { Lang.shared.el ? (EL[en] ?? en) : en }

